        let component = Component::new(
            &runtime.engine,
            format!(
                "(component (core module $fixture {core_module}) (core instance $instance (instantiate $fixture)))"
            ),
        )?;
        let host = HostFunctions::new_for_metadata_validation("resource-limit-test".to_string())?;
